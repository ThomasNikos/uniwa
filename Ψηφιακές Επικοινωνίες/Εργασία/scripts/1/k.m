% Παράμετροι σήματος
f = 60; % συχνότητα σήματος
A = 3; % πλάτος σήματος
T = 0.1; % διάρκεια σήματος

% Συχνότητες δειγματοληψίας
Fs_values = [400, 70];

% Δημιουργία ημιτονοειδούς σήματος
t = 0:1/max(Fs_values):T;
x = A * sin(2*pi*f*t);

% Δειγματοληψία του σήματος με διάφορες συχνότητες δειγματοληψίας
for i = 1:length(Fs_values)
    Fs = Fs_values(i); % συχνότητα δειγματοληψίας

    % Δειγματοληψία του σήματος
    t_sampled = 0:1/Fs:T;
    x_sampled = A * sin(2*pi*f*t_sampled);

    % Γραφική παράσταση του δειγματοληπτημένου σήματος
    figure;
    plot(t_sampled, x_sampled);
    title(['Δειγματοληπτημένο σήμα, Fs = ', num2str(Fs), ' Hz']);
    xlabel('Χρόνος (s)');
    ylabel('Τιμή σήματος');
end