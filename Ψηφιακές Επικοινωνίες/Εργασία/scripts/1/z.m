% Δημιουργία του κώδικα Hamming (7,4)
[h, g, n, k] = hammgen(3);

% Εκτύπωση των bits της κωδικής λέξης και του μηνύματος πληροφορίας
fprintf('Τα bits της κωδικής λέξης είναι: %d\n', n);
fprintf('Τα bits του μηνύματος πληροφορίας είναι: %d\n', k);

% Εκτύπωση του πίνακα ελέγχου ισοτιμίας και του γεννήτορα
fprintf('Ο πίνακας ελέγχου ισοτιμίας είναι:\n');
disp(h);
fprintf('Ο γεννήτορας είναι:\n');
disp(g);

% Δημιουργία όλων των πιθανών δυαδικών μηνυμάτων
mes = de2bi(0:(2^k - 1), 'left-msb');

% Κωδικοποίηση των μηνυμάτων
coded_mes = encode(mes, n, k, 'hamming');

% Επαλήθευση της ελάχιστης απόστασης
min_dist = gfweight(coded_mes, 'hamming');
fprintf('Η ελάχιστη απόσταση του κώδικα είναι: %d\n', min_dist);