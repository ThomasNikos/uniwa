% Σήμα ομιλίας
[x, Fs] = audioread('3WORDS.WAV');

% Παράμετροι σήματος
Ac = 1; % πλάτος φέροντος
fc = 100; % συχνότητα φέροντος
t = 0:1/Fs:(length(x)-1)/Fs; % άξονας χρόνου

% Διαφορά φάσης
delta_phi = 0.1*pi;

% Δημιουργία μη ιδανικού τοπικού ταλαντωτή
c = Ac * cos(2*pi*fc*t + delta_phi);

% Αποδιαμόρφωση του σήματος
y = x .* c;

% Φιλτράρισμα του σήματος με χαμηλοπερατό φίλτρο Butterworth
[b, a] = butter(10, fc/(Fs/2));
y_filtered = filter(b, a, y);

% Γραφική παράσταση του αποδιαμορφωμένου σήματος
figure;
plot(t, y_filtered);
title('Αποδιαμορφωμένο σήμα');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');

% Ηχητικό σήμα
sound(y_filtered, Fs);
