% Παράμετροι σήματος
Fs = 1200; % συχνότητα δειγματοληψίας
T = 1/Fs; % περίοδος δειγματοληψίας
t = 0:T:0.02; % άξονας χρόνου

% Δημιουργία σήματος
x = 2*sin(200*pi*t) + 5*cos(100*pi*t);

% Κβάντιση του σήματος
x_min = min(x);
x_max = max(x);
levels = linspace(x_min, x_max, 5);
[x_quant, ~] = quantiz(x, levels(1:end-1), levels);

% Κωδικοποίηση των κβαντισμένων τιμών του σήματος σε δυαδικές ακολουθίες
x_bin = de2bi(x_quant);

% Γραφική παράσταση του αρχικού σήματος και του κβαντισμένου σήματος
figure;
hold on;
plot(t, x, 'b');
stairs(t, levels(x_quant+1), 'r');
title('Αρχικό και κβαντισμένο σήμα');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');
legend('Αρχικό σήμα', 'Κβαντισμένο σήμα');