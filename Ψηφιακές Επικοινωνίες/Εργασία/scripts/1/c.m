% Παράμετροι σήματος
Fs = 80; % συχνότητα δειγματοληψίας
T = 1/Fs; % περίοδος δειγματοληψίας
L = 0.8*Fs; % συνολικός αριθμός δειγμάτων
t = (0:L-1)*T; % άξονας χρόνου

% Δημιουργία σήματος
x = 3*cos(4*pi*t) + 2*cos(8*pi*t) + sin(12*pi*t);

% Γραφική παράσταση του σήματος στο πεδίο του χρόνου
figure;
plot(t, x);
title('Σήμα στο πεδίο του χρόνου');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');

% Υπολογισμός του FFT
Nf = 2^ceil(log2(L)); % αριθμός σημείων FFT
y = fft(x, Nf);

% Υπολογισμός του φάσματος πλάτους
P2 = abs(y/Nf);
P1 = P2(1:Nf/2+1);
P1(2:end-1) = 2*P1(2:end-1);

f = Fs*(0:(Nf/2))/Nf;

% Γραφική παράσταση του φάσματος πλάτους
figure;
plot(f, P1);
title('Φάσμα πλάτους του σήματος');
xlabel('Συχνότητα (Hz)');
ylabel('|P1(f)|');

% Ανάλυση συχνοτήτων Fourier
Fourier_resolution = Fs/Nf;
disp(['Ανάλυση συχνοτήτων Fourier = ', num2str(Fourier_resolution), ' Hz']);