% Διαβάστε το σήμα ομιλίας
[x, Fs] = audioread('3WORDS.WAV');

% Ακούστε το σήμα
sound(x, Fs);

% Γραφική παράσταση της κυματομορφής του σήματος
figure;
plot((1:length(x))/Fs, x);
title('Κυματομορφή σήματος ομιλίας');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');

% Υπολογισμός του FFT
y = fft(x);

% Υπολογισμός του φάσματος πλάτους
P2 = abs(y/length(x));
P1 = P2(1:length(x)/2+1);
P1(2:end-1) = 2*P1(2:end-1);

f = Fs*(0:(length(x)/2))/length(x);

% Γραφική παράσταση του φάσματος πλάτους
figure;
plot(f, P1);
title('Φάσμα πλάτους του σήματος ομιλίας');
xlabel('Συχνότητα (Hz)');
ylabel('|P1(f)|');

% Αποθηκεύστε σε νέο διάνυσμα μόνο τα πρώτα 50000 δείγματα του σήματος ομιλίας
x2 = x(1:50000);

% Ακούστε το νέο σήμα
sound(x2, Fs);
