% Παράμετροι σήματος
Am = 0.5; % πλάτος σήματος πληροφορίας
fm = 2; % συχνότητα σήματος πληροφορίας
Ac = 1; % πλάτος φέροντος
fc = 100; % συχνότητα φέροντος
t = 0:0.001:1; % άξονας χρόνου

% Δημιουργία σήματος πληροφορίας
s = Am * sin(2*pi*fm*t);

% Δημιουργία φέροντος
c = Ac * cos(2*pi*fc*t);

% Διαμόρφωση AM
y = (Ac + s) .* cos(2*pi*fc*t);

% Γραφική παράσταση του σήματος πληροφορίας, του φέροντος και του διαμορφωμένου σήματος
figure;
subplot(3,1,1);
plot(t, s);
title('Σήμα πληροφορίας');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');

subplot(3,1,2);
plot(t, c);
title('Φέρον');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');

subplot(3,1,3);
plot(t, y);
hold on;
plot(t, Ac + s, 'r--'); % περιβάλλουσα
hold off;
title('Διαμορφωμένο σήμα και περιβάλλουσα');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');
legend('Διαμορφωμένο σήμα', 'Περιβάλλουσα');
