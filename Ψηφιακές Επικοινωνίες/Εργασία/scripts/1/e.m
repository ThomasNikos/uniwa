% Παράμετροι σήματος
Fs = 2000; % συχνότητα δειγματοληψίας
T = 1/Fs; % περίοδος δειγματοληψίας
t = 0:T:1.5; % άξονας χρόνου
f = 40; % συχνότητα ημιτόνου
A = 12; % πλάτος ημιτόνου
phi = 2*pi/3; % φάση ημιτόνου

% Δημιουργία σήματος
x = A * cos(2*pi*f*t + phi);

% Γραφική παράσταση του σήματος στο πεδίο του χρόνου
figure;
plot(t, x);
title('Σήμα στο πεδίο του χρόνου');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');

% Υπολογισμός του FFT
N = length(t); % αριθμός σημείων σήματος
y = fft(x);

% Υπολογισμός του φάσματος πλάτους
P2 = abs(y/N);
P1 = P2(1:N/2+1);
P1(2:end-1) = 2*P1(2:end-1);

f = Fs*(0:(N/2))/N;

% Γραφική παράσταση του φάσματος πλάτους
figure;
plot(f, P1);
title('Φάσμα πλάτους του σήματος');
xlabel('Συχνότητα (Hz)');
ylabel('|P1(f)|');
