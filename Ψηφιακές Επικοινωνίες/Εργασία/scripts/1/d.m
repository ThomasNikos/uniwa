% Παράμετροι σήματος
Fs = 100; % συχνότητα δειγματοληψίας
T = 1/Fs; % περίοδος δειγματοληψίας
t = -0.5:T:0.5; % άξονας χρόνου
sigma = 0.1; % τυπική απόκλιση

% Δημιουργία σήματος
g = (1/(sqrt(2*pi*sigma^2))) * exp(-(t.^2)/(2*sigma^2));

% Γραφική παράσταση του σήματος στο πεδίο του χρόνου
figure;
plot(t, g);
title('Σήμα στο πεδίο του χρόνου');
xlabel('Χρόνος (s)');
ylabel('Τιμή σήματος');

% Υπολογισμός του FFT
N = length(t); % αριθμός σημείων σήματος
m = 2^nextpow2(N); % αριθμός σημείων FFT
y = fft(g, m);

% Υπολογισμός του φάσματος πλάτους
P2 = abs(y/m);
P1 = P2(1:m/2+1);
P1(2:end-1) = 2*P1(2:end-1);

f = Fs*(0:(m/2))/m;

% Γραφική παράσταση του φάσματος πλάτους
figure;
plot(f, P1);
title('Φάσμα πλάτους του σήματος');
xlabel('Συχνότητα (Hz)');
ylabel('|P1(f)|');

% Εκτύπωση του m
disp(['Το m είναι ', num2str(m)]);
