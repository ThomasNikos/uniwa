% Παράμετροι σήματος
S_N0 = 200; % λόγος S/N0
B = 1:300000; % εύρος ζώνης συχνοτήτων του καναλιού

% Υπολογισμός της χωρητικότητας του καναλιού
C = B .* log2(1 + S_N0);

% Γραφική παράσταση της χωρητικότητας του καναλιού
figure;
semilogx(B, C);
title('Χωρητικότητα καναλιού σε συνάρτηση με το εύρος ζώνης συχνοτήτων');
xlabel('Εύρος ζώνης συχνοτήτων (Hz)');
ylabel('Χωρητικότητα καναλιού (bits/sec)');